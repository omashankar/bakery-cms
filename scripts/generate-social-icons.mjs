/**
 * Generates `components/shared/social-icon-paths.ts` from installed icon sets.
 *
 * Run:  node scripts/generate-social-icons.mjs
 *
 * Why generate rather than import at runtime: `simple-icons` ships one ESM
 * module carrying every icon it knows (thousands), and its per-icon subpaths are
 * raw `.svg` files rather than modules — so importing it from a client component
 * risks dragging the whole set into the browser bundle for the sake of eight
 * glyphs. Both packages stay devDependencies and the paths are checked in.
 *
 * Why generate rather than write the paths by hand: I tried that first, and the
 * result was wrong in ways no diff shows — Twitter had a subpath wound the wrong
 * way, so it subtracted and punched a hole through one arm; Instagram collapsed
 * to a solid square with its lens and flash contributing nothing. Icon path data
 * has to be copied from a canonical source, not recalled.
 *
 * Two sources because no single one covers all eight: `simple-icons` (CC0) does
 * not carry LinkedIn, and `bootstrap-icons` (MIT) does. They use different
 * viewBoxes, so each entry records its own.
 */
import { readFileSync, writeFileSync } from "node:fs";

/** platform -> the .svg file to read it from, per package. */
const SOURCES = [
  {
    package: "simple-icons",
    license: "CC0-1.0",
    dir: "node_modules/simple-icons/icons",
    icons: {
      Instagram: "instagram",
      Facebook: "facebook",
      WhatsApp: "whatsapp",
      YouTube: "youtube",
      Twitter: "x",
      Pinterest: "pinterest",
      TikTok: "tiktok",
    },
  },
  {
    package: "bootstrap-icons",
    license: "MIT",
    dir: "node_modules/bootstrap-icons/icons",
    icons: { LinkedIn: "linkedin" },
  },
];

/** The single `d` and the viewBox out of a one-path icon file. */
function readIcon(dir, file) {
  const svg = readFileSync(`${dir}/${file}.svg`, "utf8");

  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1) {
    throw new Error(`${file}.svg has ${paths.length} paths; expected exactly 1`);
  }

  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (!viewBox) throw new Error(`${file}.svg has no viewBox`);

  return { path: paths[0], viewBox };
}

const entries = [];
for (const source of SOURCES) {
  for (const [platform, file] of Object.entries(source.icons)) {
    const { path, viewBox } = readIcon(source.dir, file);
    entries.push({ platform, path, viewBox, from: `${source.package} (${source.license})` });
  }
}

const body = entries
  .map(
    (e) =>
      `  // ${e.from}\n  ${e.platform}: {\n    viewBox: "${e.viewBox}",\n    path: "${e.path}",\n  },`
  )
  .join("\n");

const file = `// GENERATED by scripts/generate-social-icons.mjs — do not edit by hand.
// Re-run that script to update, and never hand-edit a path: it is the one kind
// of change a code review cannot catch.

export interface SocialIcon {
  /** Each source uses its own coordinate space, so it travels with the path. */
  viewBox: string;
  path: string;
}

/** Brand glyph per platform, copied verbatim from the packages named below. */
export const SOCIAL_ICON_PATHS: Record<string, SocialIcon> = {
${body}
};
`;

writeFileSync("components/shared/social-icon-paths.ts", file, "utf8");
console.log(`wrote ${entries.length} icon paths`);
